  function finishIfNeeded() {
    if (!availableMoves(state).length) {
      state.over = true;
      state.turn = null;
    }
  }

  function onPlayerMove(move) {
    if (state.lock || state.over || state.turn !== 'p1') return;
    var captured = applyMove(state, move, 'p1');
    if (captured < 0) return;
    finishIfNeeded();
    if (state.over) {
      setStatus(outcomeKey(), true);
      renderBoard();
      return;
    }
    if (captured > 0) {
      state.turn = 'p1';
      setStatus(captured === 1 ? 'demo.msgSingleCapture' : 'demo.msgDoubleCapture', true);
      renderBoard();
      return;
    }
    state.turn = 'bot';
    state.lock = true;
    setStatus('demo.msgBotThinking', true);
    renderBoard();
    window.clearTimeout(botTimer);
    botTimer = window.setTimeout(function () {
      runBot();
      state.lock = false;
      finishIfNeeded();
      setStatus(state.over ? outcomeKey() : 'demo.msgYourTurnAfterBot', true);
      renderBoard();
    }, motionDelay());
  }

  function resetBoard() {
    window.clearTimeout(botTimer);
    state = createState();
    setStatus('demo.msgInitial', true);
    renderBoard();
  }

  function initBoard() {
    var reset = document.getElementById('reset-board');
    if (!reset) return;
    state = createState();
    setStatus('demo.msgInitial', false);
    renderBoard();
    reset.addEventListener('click', resetBoard);
  }

