      if (!href || href.charAt(0) === '#') return;
      var hash = '';
      var hashAt = href.indexOf('#');
      if (hashAt >= 0) {
        hash = href.slice(hashAt);
        href = href.slice(0, hashAt);
      }
      var site =
        href.indexOf('privacy-policy.html') >= 0 ||
        href.indexOf('index.html') >= 0 ||
        href.indexOf('https://regardgames.github.io/pontinhos') === 0;
      if (!site) return;
